// Why forwardRef: this Button was scaffolded from shadcn's React-19
// generation, which relies on React 19's automatic ref-as-prop behavior.
// the base app is on React 18, where function components don't receive refs unless
// wrapped in forwardRef. Without this, `<PopoverTrigger asChild><Button/>`
// composition silently drops the ref, and Floating UI can't measure the
// trigger - popovers stay parked off-screen at their placeholder transform.
const Button = React.forwardRef<
  HTMLButtonElement,
  React.ComponentProps<"button"> &
    VariantProps<typeof buttonVariants> & {
      asChild?: boolean
    }
>(function Button(
  { className, variant = "default", size = "default", asChild = false, ...props },
  ref,
) {
  const Comp = asChild ? Slot.Root : "button"

  return (
    <Comp
      ref={ref}
      data-slot="button"
      data-variant={variant}
      data-size={size}
      className={cn(buttonVariants({ variant, size, className }))}
      {...props}
    />
  )
})

export { Button, buttonVariants }
